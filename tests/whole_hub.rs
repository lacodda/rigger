//! Nothing left over: the record holds every file of every hub, so the
//! directory the hubs lie in can be deleted and written back.
//!
//! Three kinds of file used to live in a hub alone, and each is a test here:
//! the files that are not texts (a sound, a scrape, a script), the texts of a
//! project taken out of the work, and the line's own files in the directory
//! every project's hub lies in. The fourth test is the promise itself:
//! `doctor --hubs` says whether the hubs may go, and `export --all` brings
//! them back.
//!
//! Fixtures are synthetic: made-up projects, made-up files.

use std::path::{Path, PathBuf};

use assert_cmd::Command;
use serde_json::Value;

fn rigger(data: &Path) -> Command {
    let mut cmd = Command::cargo_bin("rigger").unwrap();
    cmd.env("RIGGER_DATA_DIR", data);
    cmd
}

fn output(data: &Path, args: &[&str]) -> String {
    let out = rigger(data).args(args).assert().success();
    String::from_utf8(out.get_output().stdout.clone()).unwrap()
}

fn json(data: &Path, args: &[&str]) -> Value {
    let mut all: Vec<&str> = args.to_vec();
    all.push("--json");
    serde_json::from_str(&output(data, &all)).unwrap()
}

fn refusal(data: &Path, args: &[&str]) -> String {
    let out = rigger(data).args(args).assert().failure();
    String::from_utf8(out.get_output().stderr.clone()).unwrap()
}

const PLAN: &str = "# План\n\n## v0.2.0 · Второй\n\n- [ ] сделать одно\n";
const CHANGES: &str = "# Изменения\n\n## v0.1.0 · Первый — выпущена 2026-09-01\n\nСделано.\n";
const JOURNAL: &str = "# Решения\n\nКак ведётся журнал.\n\n## 2026-09-01 · Основание\n\nПервое решение.\n";

/// Bytes no text reader would keep as they are: a carriage return without
/// its line feed, a NUL, a byte that is not UTF-8.
const SOUND: &[u8] = b"RIFF\x00\x01\r\x02\xff\xfe\r\n\x00tail";

/// A recorded project whose hub lies in `hubs/<name>`, holding a plan, a
/// changelog and a decisions journal, read into the record and handed over
/// to it - the way every hub of a line stands once it is a view.
fn project(data: &Path, name: &str) -> PathBuf {
    let root = data.join("work").join(name);
    std::fs::create_dir_all(&root).unwrap();
    rigger(data).args(["project", "add"]).arg(&root).assert().success();
    let hub = data.join("hubs").join(name);
    std::fs::create_dir_all(&hub).unwrap();
    std::fs::write(hub.join("План.md"), PLAN).unwrap();
    std::fs::write(hub.join("Изменения.md"), CHANGES).unwrap();
    std::fs::write(hub.join("Решения.md"), JOURNAL).unwrap();
    rigger(data).args(["import", name, "--hub"]).arg(&hub).assert().success();
    rigger(data).args(["export", name, "--adopt"]).assert().success();
    hub
}

fn setup() -> tempfile::TempDir {
    let data = tempfile::tempdir().unwrap();
    rigger(data.path()).arg("init").assert().success();
    data
}

fn write(path: &Path, bytes: &[u8]) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

fn drift(doctor: &Value) -> Vec<(String, String, String)> {
    doctor["hubs"]
        .as_array()
        .unwrap()
        .iter()
        .map(|d| {
            (
                d["project"].as_str().unwrap().to_string(),
                d["file"].as_str().unwrap().to_string(),
                d["state"].as_str().unwrap().to_string(),
            )
        })
        .collect()
}

fn loses_nothing(data: &Path) -> bool {
    json(data, &["doctor", "--hubs"])["hubs_verdict"]["loses_nothing"].as_bool().unwrap()
}

#[test]
fn every_file_of_a_hub_that_is_not_a_text_is_kept_byte_for_byte() {
    let data = setup();
    let hub = project(data.path(), "alpha");
    write(&hub.join("Исследования/2026-09-01 — Голоса/voice.wav"), SOUND);
    write(&hub.join("Исследования/bench/result.json"), b"");
    write(&hub.join("Сырьё/script.py"), b"print('one')\r\nprint('two')\r\n");
    // Markdown that holds nothing to read as a text is still a file the hub
    // would lose: an empty note, and a view the record wrote, copied away.
    write(&hub.join("Пустая заметка.md"), b"");
    write(
        &hub.join("Архив/План.md"),
        b"<!-- generated by rigger; edits here are overwritten -->\n\n# old\n",
    );

    let report = json(data.path(), &["import", "alpha", "--hub", hub.to_str().unwrap()]);
    assert_eq!(report["files_added"], 5, "{report}");
    assert_eq!(report["texts_only"], false, "{report}");

    // Read again unchanged, nothing changes.
    let again = output(data.path(), &["import", "alpha", "--hub", hub.to_str().unwrap()]);
    assert!(again.contains("nothing changed"), "{again}");

    // A file that changed is taken in again, as an update.
    write(&hub.join("Исследования/2026-09-01 — Голоса/voice.wav"), b"RIFF changed");
    let changed = json(data.path(), &["import", "alpha", "--hub", hub.to_str().unwrap()]);
    assert_eq!(changed["files_updated"], 1, "{changed}");
    assert_eq!(changed["files_added"], 0, "{changed}");
    write(&hub.join("Исследования/2026-09-01 — Голоса/voice.wav"), SOUND);
    rigger(data.path()).args(["import", "alpha", "--hub"]).arg(&hub).assert().success();

    let files = json(data.path(), &["doc", "files", "alpha"]);
    let listed: Vec<&str> = files["files"].as_array().unwrap().iter().map(|f| f["path"].as_str().unwrap()).collect();
    assert!(listed.contains(&"Исследования/2026-09-01 — Голоса/voice.wav"), "{files}");
    assert!(listed.contains(&"Пустая заметка.md"), "{files}");
    let voice = files["files"]
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["path"] == "Исследования/2026-09-01 — Голоса/voice.wav")
        .unwrap();
    assert_eq!(voice["bytes"], SOUND.len(), "{files}");

    // Written into an empty directory, every file comes back as it was.
    let out = data.path().join("out");
    std::fs::create_dir_all(&out).unwrap();
    rigger(data.path()).args(["export", "alpha", "--docs", "--hub"]).arg(&out).assert().success();
    for rel in [
        "Исследования/2026-09-01 — Голоса/voice.wav",
        "Исследования/bench/result.json",
        "Сырьё/script.py",
        "Пустая заметка.md",
        "Архив/План.md",
    ] {
        assert_eq!(std::fs::read(out.join(rel)).unwrap(), std::fs::read(hub.join(rel)).unwrap(), "{rel}");
    }

    // A file removed from the record is gone from the listing.
    let removed = json(data.path(), &["doc", "remove", "alpha", "Сырьё/script.py"]);
    assert_eq!(removed["removed"]["file"], "Сырьё/script.py", "{removed}");
    let files = json(data.path(), &["doc", "files", "alpha"]);
    assert!(!files.to_string().contains("script.py"), "{files}");
}

#[test]
fn a_file_too_large_to_keep_stays_in_the_hub_and_is_named() {
    let data = setup();
    let hub = project(data.path(), "alpha");
    let big = hub.join("video.mp4");
    let file = std::fs::File::create(&big).unwrap();
    file.set_len(64 * 1024 * 1024 + 1).unwrap();
    drop(file);

    let report = json(data.path(), &["import", "alpha", "--hub", hub.to_str().unwrap()]);
    assert_eq!(report["files_added"], 0, "{report}");
    let warned = report["warnings"].as_array().unwrap().iter().any(|w| w.as_str().unwrap().contains("video.mp4"));
    assert!(warned, "the import must say what it passed over: {report}");

    let doctor = json(data.path(), &["doctor", "--hubs"]);
    assert!(drift(&doctor).contains(&("alpha".into(), "video.mp4".into(), "too-large".into())), "{doctor}");
    assert_eq!(doctor["hubs_verdict"]["loses_nothing"], false, "{doctor}");
}

#[test]
fn a_retired_project_is_read_for_its_texts_and_files_alone() {
    let data = setup();
    let hub = project(data.path(), "attic");
    rigger(data.path())
        .args(["project", "retire", "attic", "--why", "Nobody climbs up there any more."])
        .assert()
        .success();
    write(&hub.join("Стайл-гайд.md"), "# Стайл-гайд\n\nКак писать.\n".as_bytes());
    write(&hub.join("Сиды/seed.json"), b"{\"seed\": 1}");
    // A stage written into the plan after the retirement is not history to
    // keep; the schema would refuse it, and the reading does not ask.
    std::fs::write(hub.join("План.md"), format!("{PLAN}\n## v0.9.0 · Поздний\n\n- [ ] поздно\n")).unwrap();

    let said = output(data.path(), &["import", "attic", "--hub", hub.to_str().unwrap()]);
    assert!(said.contains("is retired since"), "{said}");
    assert!(said.contains("only its texts and files were read"), "{said}");
    let docs = json(data.path(), &["doc", "list", "attic"]);
    assert!(docs.to_string().contains("Стайл-гайд.md"), "{docs}");
    let files = json(data.path(), &["doc", "files", "attic"]);
    assert!(files.to_string().contains("Сиды/seed.json"), "{files}");
    let plan = refusal(data.path(), &["version", "show", "attic", "v0.9.0"]);
    assert!(!plan.is_empty(), "the late stage must not be in the record");
}

/// The line's own place: the directory every hub lies in, read for what is
/// in it outside those hubs.
fn line_root(data: &Path) -> PathBuf {
    let root = data.join("hubs");
    write(&root.join("brand/README.md"), "# Реестр знаков\n\nКоды и цвета.\n".as_bytes());
    write(&root.join("brand/svg/mark.svg"), b"<svg xmlns=\"http://www.w3.org/2000/svg\"/>");
    write(&root.join("_Исследования/2026-09-01 — Сверка.md"), "# Сверка\n\nЧто нашли.\n".as_bytes());
    write(&root.join("Календарь.md"), "# Календарь\n\nНеделя за неделей.\n".as_bytes());
    // In the line's place no name is a part of the record: its README is
    // the owner's prose.
    write(&root.join("README.md"), "# Хабы\n\nЧто здесь лежит.\n".as_bytes());
    rigger(data).args(["profile", "set", "--hubs"]).arg(&root).assert().success();
    root
}

#[test]
fn the_line_keeps_its_own_files_in_the_directory_the_hubs_lie_in() {
    let data = setup();
    project(data.path(), "alpha");
    let root = line_root(data.path());
    // A hub no project names: somebody's plan, not the line's text.
    write(&root.join("stray/План.md"), PLAN.as_bytes());

    // Before the line's place is read, its files are in nobody's record.
    let doctor = json(data.path(), &["doctor", "--hubs"]);
    let found = drift(&doctor);
    assert!(found.contains(&("line".into(), "brand/README.md".into(), "not-held".into())), "{doctor}");
    assert!(found.contains(&("line".into(), "stray".into(), "unrecorded-hub".into())), "{doctor}");
    assert!(
        !found.iter().any(|(_, file, _)| file.starts_with("alpha")),
        "a project's hub is not the line's: {doctor}"
    );
    assert_eq!(doctor["hubs_verdict"]["loses_nothing"], false, "{doctor}");

    // Read with no hub named: the line's hub is where the profile keeps them.
    let said = output(data.path(), &["import", "line"]);
    assert!(said.contains("the line's own place"), "{said}");
    assert!(said.contains("stray"), "the hub left out is named: {said}");

    let docs = json(data.path(), &["doc", "list", "line"]);
    let files: Vec<&str> = docs.as_array().unwrap().iter().filter_map(|d| d["file"].as_str()).collect();
    for wanted in ["brand/README.md", "_Исследования/2026-09-01 — Сверка.md", "Календарь.md", "README.md"] {
        assert!(files.contains(&wanted), "{wanted} is a text of the line: {docs}");
    }
    assert!(!files.iter().any(|f| f.starts_with("alpha/") || f.starts_with("stray/")), "{docs}");
    let research = docs
        .as_array()
        .unwrap()
        .iter()
        .find(|d| d["file"] == "_Исследования/2026-09-01 — Сверка.md")
        .unwrap();
    assert_eq!(research["kind"], "research", "{docs}");
    assert!(json(data.path(), &["doc", "files", "line"]).to_string().contains("brand/svg/mark.svg"));

    // The stray is still somebody's hub, and still not held.
    assert!(!loses_nothing(data.path()));
    std::fs::remove_dir_all(root.join("stray")).unwrap();
    assert!(loses_nothing(data.path()), "{}", output(data.path(), &["doctor", "--hubs"]));
    let said = output(data.path(), &["doctor", "--hubs"]);
    assert!(said.contains("deleting it loses nothing"), "{said}");
}

#[test]
fn a_decisions_journal_is_vouched_for_only_when_every_entry_is_in_the_record() {
    let data = setup();
    let hub = project(data.path(), "alpha");
    assert!(loses_nothing(data.path()), "{}", output(data.path(), &["doctor", "--hubs"]));

    std::fs::write(hub.join("Решения.md"), format!("{JOURNAL}\n## 2026-09-02 · Второе\n\nНаписано руками.\n")).unwrap();
    let doctor = json(data.path(), &["doctor", "--hubs"]);
    assert!(drift(&doctor).contains(&("alpha".into(), "Решения.md".into(), "not-held".into())), "{doctor}");
    rigger(data.path()).args(["import", "alpha"]).assert().success();
    assert!(loses_nothing(data.path()), "{}", output(data.path(), &["doctor", "--hubs"]));
}

#[test]
fn deleted_hubs_come_back_from_the_record() {
    let data = setup();
    let alpha = project(data.path(), "alpha");
    write(&alpha.join("Исследования/2026-09-01 — Голоса/voice.wav"), SOUND);
    write(&alpha.join("Исследования/2026-09-01 — Голоса.md"), "# Голоса\n\nОбразцы рядом.\n".as_bytes());
    let attic = project(data.path(), "attic");
    write(&attic.join("Стайл-гайд.md"), "# Стайл-гайд\n\nКак писать.\n".as_bytes());
    rigger(data.path()).args(["import", "alpha"]).assert().success();
    rigger(data.path()).args(["import", "attic"]).assert().success();
    rigger(data.path()).args(["project", "retire", "attic", "--why", "Done."]).assert().success();
    let root = line_root(data.path());
    rigger(data.path()).args(["import", "line"]).assert().success();
    assert!(loses_nothing(data.path()), "{}", output(data.path(), &["doctor", "--hubs"]));

    // One hub gone, written back where the record says it lies.
    std::fs::remove_dir_all(&alpha).unwrap();
    output(data.path(), &["export", "alpha", "--docs"]);
    assert_eq!(std::fs::read(alpha.join("Исследования/2026-09-01 — Голоса/voice.wav")).unwrap(), SOUND);
    assert!(alpha.join("План.md").is_file());

    // A directory named outright has to be there: a typo would become the hub.
    let typo = data.path().join("nowhere");
    let refused = refusal(data.path(), &["export", "alpha", "--hub", typo.to_str().unwrap()]);
    assert!(refused.contains("is not a directory"), "{refused}");

    // All of them gone, all of them back: the retired project's and the
    // line's own files among them.
    std::fs::remove_dir_all(&root).unwrap();
    let wrote = json(data.path(), &["export", "--all", "--docs"]);
    let hubs = wrote["hubs"].as_array().unwrap();
    for name in ["alpha", "attic", "line"] {
        let hub = hubs.iter().find(|h| h["project"] == name).unwrap_or_else(|| panic!("{name}: {wrote}"));
        assert_eq!(hub["made"], true, "{wrote}");
    }
    assert_eq!(std::fs::read(alpha.join("Исследования/2026-09-01 — Голоса/voice.wav")).unwrap(), SOUND);
    assert!(attic.join("Стайл-гайд.md").is_file());
    assert!(root.join("brand/svg/mark.svg").is_file());
    assert!(root.join("_Исследования/2026-09-01 — Сверка.md").is_file());
    // The line's place gets its texts and no plan of nothing.
    assert!(!root.join("План.md").exists());
    assert!(loses_nothing(data.path()), "{}", output(data.path(), &["doctor", "--hubs"]));

    // And a second run writes nothing.
    let again = output(data.path(), &["export", "--all", "--docs"]);
    assert!(again.contains("Every hub is already what the record says"), "{again}");
}

#[test]
fn export_all_refuses_a_file_kept_by_hand_before_it_writes_any() {
    let data = setup();
    let alpha = project(data.path(), "alpha");
    let beta = project(data.path(), "beta");
    std::fs::remove_file(alpha.join("Дневник.md")).unwrap();
    // beta's plan is kept by hand again: no mark, and something the record
    // would write differently.
    std::fs::write(beta.join("План.md"), format!("{PLAN}\nСтрока, написанная руками.\n")).unwrap();

    let refused = refusal(data.path(), &["export", "--all"]);
    assert!(refused.contains("beta: План.md"), "{refused}");
    assert!(!alpha.join("Дневник.md").exists(), "nothing is written when one hub is refused");

    rigger(data.path()).args(["export", "--all", "--adopt"]).assert().success();
    assert!(alpha.join("Дневник.md").is_file());
}
